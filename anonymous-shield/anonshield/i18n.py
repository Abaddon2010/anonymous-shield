def _base_dict(lang: str) -> dict:
    l = (lang or "").lower().replace("_", "-")
    for cand in (l, l.split("-")[0]):
        if cand.startswith("pt"):
            return _PT
        if cand.startswith("es"):
            return _ES
        if cand.startswith("en"):
            return _EN
    return _EN


def t(lang: str, key: str) -> str:
    l = (lang or "").lower().replace("_", "-")
    pack = _PACKS_NORM.get(l) or _PACKS_NORM.get(l.split("-")[0])
    if pack and key in pack:
        return pack[key]
    d = _base_dict(lang)
    if key in d:
        return d[key]
    return _EN.get(key, key)


def is_supported(lang: str) -> bool:
    l = (lang or "").lower().replace("_", "-")
    return l in _LANG_CODES or l.split("-")[0] in _LANG_CODES


